export async function legalPage(app, kind) {
  const page = PAGES[kind];
  const info = await loadInfo();
  mount(app, topbar(), h('main', { class: 'legal' },
    h('article', { class: 'card legal-card' },
      h('h1', {}, page.title),
      h('p', { class: 'muted small' }, `עודכן: ${UPDATED}`),
      page.body(info),
      h('nav', { class: 'legal-nav row wrap' },
        Object.entries(PAGES).filter(([k]) => k !== kind).map(([k, v]) => h('a', { class: 'btn ghost small', href: `#/legal/${k}` }, v.title))))));
}
