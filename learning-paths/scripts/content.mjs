// Checks the ready-made paths in content/paths/*.json and builds content/library-data.js,
// which the server and the demo load.
//   node scripts/content.mjs                 check every file, then write library-data.js
//   node scripts/content.mjs <file.json>...  check only these files (writes nothing)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as v from '../validate.js';
import { GRADES } from '../ai-prompt.js';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'content', 'paths');
export const SUBJECTS = ['עברית', 'חשבון', 'אנגלית', 'מדעים', 'היסטוריה', 'גאוגרפיה', 'תנ״ך', 'אזרחות', 'כישורי חיים', 'אחר'];
const NOT_IN_LIBRARY = ['link', 'hotspot']; // a dead link or a missing picture spoils a ready-made path

export function checkPath(p, where) {
  const errors = [];
  const err = (msg) => errors.push(`${where}: ${msg}`);
  if (!/^[a-z0-9-]{3,60}$/.test(p?.slug || '')) err('slug: lowercase latin letters, digits and dashes');
  if (typeof p.title !== 'string' || !p.title.trim() || p.title.length > 120) err('title');
  if (typeof p.description !== 'string' || p.description.length > 1000) err('description');
  if (!SUBJECTS.includes(p.subject)) err(`subject must be one of ${SUBJECTS.join(', ')}`);
  if (!GRADES.includes(p.grade)) err(`grade must be one of ${GRADES.join(', ')}`);
  if (typeof p.curriculum !== 'string' || !p.curriculum.trim()) err('curriculum: the topic in the curriculum');
  if (!Number.isInteger(p.order ?? 0)) err('order must be an integer');
  let theme = null;
  try { theme = v.theme(p.theme || {}); } catch (e) { err(`theme: ${e.message}`); }
  const tasks = Array.isArray(p.tasks) ? p.tasks : [];
  if (tasks.length < 4 || tasks.length > 10) err(`4–10 tasks (has ${tasks.length})`);
  const clean = [];
  tasks.forEach((t, i) => {
    if (NOT_IN_LIBRARY.includes(t?.type)) return err(`task ${i + 1}: type ${t.type} is not used in the library`);
    try {
      clean.push(v.task(t));
    } catch (e) {
      err(`task ${i + 1} (${t?.type} "${t?.title}"): ${e.message}`);
    }
  });
  if (clean.length && new Set(clean.map((t) => t.type)).size < Math.min(4, clean.length)) err('use at least 4 different task types');
  for (let i = 1; i < clean.length; i++) if (clean[i].type === clean[i - 1].type) err(`tasks ${i} and ${i + 1} are the same type in a row`);
  return {
    errors,
    path: errors.length ? null : {
      slug: p.slug, title: p.title.trim(), description: p.description.trim(), subject: p.subject, grade: p.grade,
      curriculum: p.curriculum.trim(), order: p.order ?? 0, theme, tasks: clean,
    },
  };
}

export function loadAll(files = fs.readdirSync(dir).filter((f) => f.endsWith('.json')).map((f) => path.join(dir, f))) {
  const errors = [];
  const paths = [];
  for (const file of files) {
    let list;
    try {
      list = JSON.parse(fs.readFileSync(file, 'utf8'));
    } catch (e) {
      errors.push(`${path.basename(file)}: not valid JSON: ${e.message}`);
      continue;
    }
    if (!Array.isArray(list)) { errors.push(`${path.basename(file)}: must be a JSON array of paths`); continue; }
    list.forEach((p, i) => {
      const r = checkPath(p, `${path.basename(file)} #${i + 1} ${p?.slug || ''}`);
      errors.push(...r.errors);
      if (r.path) paths.push(r.path);
    });
  }
  const seen = new Set();
  for (const p of paths) {
    if (seen.has(p.slug)) errors.push(`duplicate slug ${p.slug}`);
    seen.add(p.slug);
  }
  return { errors, paths };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const only = process.argv.slice(2).map((f) => path.resolve(f));
  const { errors, paths } = loadAll(only.length ? only : undefined);
  if (errors.length) {
    console.error(errors.join('\n'));
    console.error(`\n${errors.length} problems`);
    process.exit(1);
  }
  const tasks = paths.reduce((n, p) => n + p.tasks.length, 0);
  console.log(`OK: ${paths.length} paths, ${tasks} tasks`);
  if (!only.length) {
    paths.sort((a, b) => a.subject.localeCompare(b.subject, 'he') || a.order - b.order || a.title.localeCompare(b.title, 'he'));
    const out = `// Generated by scripts/content.mjs from content/paths/*.json. Do not edit by hand.\nexport default ${JSON.stringify(paths)};\n`;
    fs.writeFileSync(path.join(root, 'content', 'library-data.js'), out);
    console.log('wrote content/library-data.js');
  }
}
